from tests.test_gui import _display_available, app  # noqa: E402,F401


@pytest.mark.skipif(not _display_available(), reason="no display")
def test_the_coding_page_opens_edits_and_highlights(app, tmp_path):
    (tmp_path / "main.py").write_text("def hello():\n    return 'hi'  # greet\n", encoding="utf-8")
    app._show_tab("code")
    app.update()
    page = app.pages["code"]
    page.open_folder(str(tmp_path))
    page.open_file(tmp_path / "main.py")
    editor = page.current
    assert editor is not None and editor.text.tag_ranges("Keyword") and editor.text.tag_ranges("Comment")
    editor.text.insert("end", "\nprint(hello())\n")
    app.update()
    assert editor.dirty
    page.save_current()
    assert "print(hello())" in (tmp_path / "main.py").read_text(encoding="utf-8")
    assert not editor.dirty
    editor.text.tag_add("sel", "1.0", "2.end")
    editor._comment()
    assert editor.content().startswith("# def hello")
    page.open_lesson(page.app.jarvis and __import__("jarvis.ten.coding", fromlist=["x"]).LESSONS[0])
    assert page.check_btn.winfo_manager()
